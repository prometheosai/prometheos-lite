fn main() {
    let test_cases = [
        "2026:10:22-12-00-00Z",
        "2026-10-22-12:00:00Z",
        "2026-10-22T12-00-00Z",
        "2026/10/22T12:00:00Z",
        "2026-10-22T12:00:00z",
        "2026-99-99T99:99:99Z",
        "2026-13-01T12:00:00Z",
        "2026-00-01T12:00:00Z",
        "2026-02-30T12:00:00Z",
        "2026-04-31T12:00:00Z",
        "2025-02-29T12:00:00Z",
        "2026-10-22T24:00:00Z",
        "2026-10-22T12:60:00Z",
        "2026-10-22T12:00:60Z",
        "2026-10-22T12:00:00+00:00",
        "2026-10-22T12:00:00-03:00",
        "",
        "2026-10-22",
        "2024-02-29T00:00:00Z",
        "2000-02-29T23:59:59Z",
        "2026-10-22T12:00:00Z",
    ];
    for v in test_cases {
        match chrono::DateTime::parse_from_rfc3339(v) {
            Ok(dt) => println!("PARSED: {:?} -> {:?}", v, dt),
            Err(e) => println!("ERROR:  {:?} -> {:?}", v, e),
        }
    }
}